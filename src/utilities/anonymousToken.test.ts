import { describe, expect, it } from 'vitest';
import { isValidAnonymousToken } from './anonymousToken';

describe('anonymous browser token validation', () => {
  it('accepts UUIDv4 tokens generated by crypto.randomUUID', () => {
    expect(isValidAnonymousToken('70000000-0000-4000-8000-000000000001')).toBe(true);
    expect(isValidAnonymousToken('A0000000-0000-4ABC-B000-000000000001')).toBe(true);
  });

  it.each(['', '   ', 'not-a-uuid', '70000000-0000-1000-8000-000000000001'])(
    'rejects invalid token %j',
    (token) => expect(isValidAnonymousToken(token)).toBe(false),
  );
});
